export function useStaffT() {
  const { lang } = useI18n()
  return (key: StaffKey, vars?: Record<string, string | number>) => {
    let s = (lang === 'fi' ? fi[key] : undefined) ?? en[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    return s
  }
}

export function staffHas(key: string): key is StaffKey {
  return key in en
}
