"""Build a compact digest of all Round 1 proposals.

Writes docs/02-ideation/round-1-digest.md: one table row per raw feature plus each role's
top-3 picks and hero concept (verbatim). Usage: python scripts/build_digest.py
"""
from __future__ import annotations

from aggregate_scores import IDEATION, ROLES, author, md_table, parse_features, section

ROLE_TITLES = {
    "STR": "CEO & Business Strategist",
    "PM": "Head of Product",
    "UX": "Head of Design & User Research",
    "TECH": "CTO & AI/ML Lead",
    "RAI": "Responsible AI, Privacy & Legal Lead",
    "TAL": "Talent Acquisition & International Recruitment Expert",
}


def short(text: str, limit: int = 220) -> str:
    text = " ".join(text.replace("|", "/").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def main() -> None:
    features = parse_features()
    out = [
        "# Round 1 digest (generated)",
        "",
        "Generated by `scripts/build_digest.py` from `round-1-proposals/`. Do not edit by hand.",
        f"**{len(features)} raw feature ideas** from {len({author(i) for i in features})} roles.",
        "",
        "## All raw features",
    ]
    for role in ROLES:
        rows = [f for f in features.values() if author(f["id"]) == role]
        if not rows:
            continue
        out += ["", f"### {role} — {ROLE_TITLES[role]}", ""]
        out += md_table(
            ["ID", "Feature", "One-liner", "Stage", "Users", "Pain points", "48h", "Self J1/J2/J3"],
            [[f["id"], short(f["name"], 80), short(f["fields"].get("one-liner", "")),
              short(f["fields"].get("journey stage", ""), 60), short(f["fields"].get("primary users", ""), 50),
              short(f["fields"].get("pain points addressed", ""), 40), f["fields"].get("48h prototype", "")[:1],
              "/".join(f"{x:g}" for x in f["self"]) if f["self"] else ""] for f in rows],
        )
    out += ["", "## Top-3 picks and hero concepts (verbatim)"]
    for path in sorted((IDEATION / "round-1-proposals").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        role = path.name.split("-")[0].upper()
        out += ["", f"### {role} — {ROLE_TITLES.get(role, role)}", "", "**Top 3**", "",
                section(text, "4.").strip(), "", "**Hero concept**", "", section(text, "5.").strip()]
    target = IDEATION / "round-1-digest.md"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
